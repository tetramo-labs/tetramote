const MODIFIER_FLAG: Record<number, number> = {
  0xe0: FLAG_CONTROL,
  0xe4: FLAG_CONTROL,
  0xe1: FLAG_SHIFT,
  0xe5: FLAG_SHIFT,
  0xe2: FLAG_OPTION,
  0xe6: FLAG_OPTION,
  0xe3: FLAG_COMMAND,
  0xe7: FLAG_COMMAND,
}

/** Keys that type a character: letters, digits, space, punctuation and the keypad's. */
function typesText(usage: number): boolean {
  return (
    (usage >= 0x04 && usage <= 0x27) ||
    (usage >= 0x2c && usage <= 0x38) ||
    usage === 0x64 ||
    (usage >= 0x54 && usage <= 0x57) ||
    (usage >= 0x59 && usage <= 0x63) ||
    usage === 0x67
  )
}

export type KeyAction = {send: InputEvent[]; repeat: boolean} | {type: string} | {ignore: true}

/**
 * Turns a hardware keyboard's keys into what goes to the computer. Raw sends every key by position, modifiers
 * included, so the computer's own layout makes the characters. Translated lets the phone's layout make them:
 * keys that type go as text (on iOS the phone's text field types them, so they are ignored here), and the rest,
 * or anything held with ⌘ or ⌃, still go by position. `sticky` flags (the key row's) join any key that goes by
 * position, but never turn a Translated text key into a shortcut: the text field applies them to those.
 */
export class HardwareKeys {
  private held = new Set<number>()
  private byPosition = new Set<number>()

  flags(): number {
    let flags = 0
    for (const usage of this.held) flags |= MODIFIER_FLAG[usage] ?? 0
    return flags
  }

  release() {
    this.held.clear()
    this.byPosition.clear()
  }

  handle(event: HardwareKeyEvent, mode: HardwareKeyboardMode, sticky = 0): KeyAction {
    const usage = event.usage ?? (event.code !== undefined ? ANDROID_TO_HID[event.code] : undefined)
    if (usage === undefined) return {ignore: true}
    const mac = HID_TO_MAC[usage]
    if (mac === undefined) return {ignore: true}
    const modifier = MODIFIER_FLAG[usage] !== undefined
    if (modifier) {
      if (event.down) this.held.add(usage)
      else this.held.delete(usage)
    }
    const flags = this.flags()
    const shortcut = (flags & (FLAG_COMMAND | FLAG_CONTROL)) !== 0
    const releasesByPosition = !event.down && this.byPosition.delete(usage)
    if (mode === "translated" && !modifier && typesText(usage) && !shortcut && !releasesByPosition) {
      if (event.usage !== undefined) return {ignore: true}
      if (!event.down || !event.unicode) return {ignore: true}
      return {type: String.fromCodePoint(event.unicode)}
    }
    if (event.down && !modifier) this.byPosition.add(usage)
    return {
      send: [{kind: "key", keyCode: mac, down: event.down, flags: modifier ? flags : flags | sticky}],
      repeat: event.down && !modifier,
    }
  }
}
